"""Restore pinned Qt kits/Python runtimes; prepare a Python-only iOS matrix build.

No Qt source compilation is performed. Use Python 3.13 on Intel macOS.
"""
from __future__ import annotations

import argparse
import concurrent.futures
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tarfile

HERE = Path(__file__).resolve().parent


def run(*args, **kwargs):
    return subprocess.run(list(map(str, args)), check=True, **kwargs)


def fetch(url, digest, path):
    if not path.exists():
        temporary = path.with_suffix(path.suffix + ".part")
        run("curl", "-fLsS", "--retry", "3", url, "-o", temporary)
        temporary.replace(path)
    with path.open("rb") as stream:
        actual = hashlib.file_digest(stream, "sha256").hexdigest()
    if actual != digest:
        raise SystemExit(f"Checksum mismatch: {path}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--work-root", type=Path, required=True)
    args = parser.parse_args()
    if sys.platform != "darwin" or os.geteuid() == 0 or sys.version_info[:2] != (3, 13):
        raise SystemExit("Run Python 3.13 as your normal macOS login user.")
    run("xcrun", "--sdk", "iphoneos", "--show-sdk-path")
    root = args.work_root.resolve()
    for name in ["downloads", "reports", "logs"]:
        (root / name).mkdir(parents=True, exist_ok=True)
    inputs = json.loads((HERE / "python-matrix-inputs.json").read_text())
    (root / "inputs.json").write_text(json.dumps(inputs, indent=2) + "\n")
    items = [(v["url"], v["sha256"], v["name"], root / "python" / minor)
             for minor, v in inputs["python"].items()]
    items.extend((v["url"], v["digest"].removeprefix("sha256:"), v["name"], root)
                 for v in inputs["qt_assets"] if not v["name"].startswith("pyside-setup-"))

    def prepare(item):
        url, digest, name, destination = item
        archive = root / "downloads" / name
        fetch(url, digest, archive)
        marker = root / "reports" / (name + ".extracted")
        if marker.exists():
            if marker.read_text().strip() != digest:
                raise SystemExit(f"Different extraction marker: {marker}")
            return
        destination.mkdir(parents=True, exist_ok=True)
        if name.endswith(".tar.zst"):
            # The Qt archives are generated by this repository, pinned by hash.
            # BSD tar's -I differs from GNU tar; use an explicit zstd pipeline.
            decompressor = subprocess.Popen(["zstd", "-dc", str(archive)], stdout=subprocess.PIPE)
            extracted = subprocess.run(["tar", "-xf", "-", "-C", str(destination)], stdin=decompressor.stdout)
            decompressor.stdout.close()
            if decompressor.wait() or extracted.returncode:
                raise SystemExit(f"Extraction failed: {archive}")
        else:
            with tarfile.open(archive) as bundle:
                bundle.extractall(destination, filter="data")
        marker.write_text(digest + "\n")
        print("Verified and extracted", name, flush=True)

    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
        list(pool.map(prepare, items))
    versions = json.loads((HERE / "versions.json").read_text())
    source = root / "pyside-setup"
    if not source.exists():
        run("git", "clone", "--depth", "1", "--branch", "v6.12.0", "https://github.com/pyside/pyside-setup.git", source)
    revision = subprocess.check_output(["git", "-C", str(source), "rev-parse", "HEAD"], text=True).strip()
    if revision != versions["source_revisions"]["pyside-setup"]:
        raise SystemExit("Unexpected PySide source revision")
    for info in versions["pyside_patches"]:
        patch = HERE / "patches" / info["file"]
        if hashlib.sha256(patch.read_bytes()).hexdigest() != info["sha256"]:
            raise SystemExit("Unexpected PySide patch checksum")
        base = ["patch", "-p1", "--force", "--silent", "-i", str(patch)]
        reverse = subprocess.run([*base, "--dry-run", "--reverse"], cwd=source, capture_output=True)
        if reverse.returncode:
            run(*base, "--forward", cwd=source)
    python = root / "venvs/build/bin/python"
    if not python.exists():
        run(sys.executable, "-m", "venv", python.parent.parent)
    generator = root / "downloads" / versions["host_generator_url"].rsplit("/", 1)[1]
    fetch(versions["host_generator_url"], versions["host_generator_sha256"], generator)
    run(python, "-m", "pip", "install", "setuptools==78.1.0", "packaging==24.2", "build==1.2.2.post1",
        "wheel==0.46.3", "jinja2==3.1.6", "certifi", generator)
    print("Prepared Python 3.10–3.14 runtimes and all three Qt 6.12.0 iOS 15 kits:", root)


if __name__ == "__main__":
    main()
